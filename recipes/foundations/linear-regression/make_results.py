"""Aggregate results/*.json into results.md.

No number in results.md is typed by hand. Re-run `make results` after any change and
commit whatever it produces.

Recipe-local by design: there is no shared library yet, and there should not be one
until a second recipe needs the same thing.
"""

import json
from datetime import date
from pathlib import Path

RECIPE_DIR = Path(__file__).resolve().parent
ORDER = {"manual": 0, "nn": 1}


def main():
    records = []
    for path in sorted((RECIPE_DIR / "results").glob("*.json")):
        with open(path) as f:
            records.append(json.load(f))

    if not records:
        raise SystemExit("no run records in results/ -- run `make train-manual train-nn` first")

    records.sort(key=lambda r: (r["env"]["device"], ORDER.get(r["variant"], 9)))

    # Every row must come from the same hyperparameters, or the table compares
    # things that are not comparable while reporting only one config in the header.
    configs = {json.dumps(r["config"], sort_keys=True) for r in records}
    if len(configs) > 1:
        raise SystemExit(
            "results/ holds runs with differing configs, so the table would be "
            "misleading:\n  "
            + "\n  ".join(sorted(configs))
            + "\n\nRun `make clean` and re-run the benchmark."
        )

    # Same check for the machine. Every row shares one header, so records from two
    # different Macs would silently attribute one machine's numbers to the other.
    # `device` is excluded because cpu-vs-gpu rows legitimately differ.
    machines = {
        json.dumps({k: v for k, v in r["env"].items() if k != "device"}, sort_keys=True)
        for r in records
    }
    if len(machines) > 1:
        raise SystemExit(
            "results/ holds runs from different machines or MLX versions, which this "
            "table cannot represent:\n  "
            + "\n  ".join(sorted(machines))
            + "\n\nRun `make clean` and re-run the benchmark on one machine."
        )

    env = records[0]["env"]
    cfg = records[0]["config"]

    lines = [
        "# Results",
        "",
        f"<!-- Generated by make_results.py on {date.today().isoformat()}."
        " Do not edit by hand. -->",
        "",
        f"- Machine: **{env.get('chip', 'unknown')}**"
        + (f", {env['memory_gb']} GB unified memory" if env.get("memory_gb") else ""),
        f"- `{env['platform']}` ({env['machine']})",
        f"- Python {env['python']}, MLX {env['mlx']}",
        f"- Optimizer `{cfg['optimizer']}`, lr {cfg['learning_rate']}, "
        f"{cfg['num_iters']} iterations, seed {cfg['seed']}",
        "",
        "| Variant | Device | RMSE | MAE | R² | Time (s) | it/s | Peak mem |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]

    for r in records:
        m, t = r["metrics"], r["timing"]
        peak = r["peak_memory_bytes"]
        peak_s = f"{peak / 1e6:.1f} MB" if peak else "n/a"
        lines.append(
            f"| {r['variant']} | {r['env']['device']} | "
            f"${m['rmse']:,.0f} | ${m['mae']:,.0f} | {m['r2']:.4f} | "
            f"{t['seconds']:.3f} | {t['iters_per_second']:,.0f} | {peak_s} |"
        )

    lines += [
        "",
        "RMSE and MAE are in dollars: predictions are converted out of standardised",
        "space before scoring, and both variants use the same metric code in",
        "`evaluate.py`.",
        "",
    ]

    out = RECIPE_DIR / "results.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(RECIPE_DIR.parent.parent.parent)}")


if __name__ == "__main__":
    main()
